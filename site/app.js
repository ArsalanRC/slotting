/* Geometry, matching `Layout` defaults: 3.6m aisle pitch, 1.2m bays. Drawn in
   SVG units where one metre is one unit, so the picture is to scale. */
const PITCH = 3.6, BAY = 1.2;
const DEPTH = DATA.bays * BAY;
const CELL = 14, GAP = 6, PAD = 10, DOCK = 16;
const W = PAD * 2 + DATA.aisles * CELL * 2 + (DATA.aisles - 1) * GAP;
const H = PAD * 2 + DATA.bays * CELL + DOCK;

const xOf = (aisle, side) => PAD + aisle * (CELL * 2 + GAP) + (side === "R" ? CELL : 0);
const yOf = (bay) => PAD + bay * CELL;
const ns = "http://www.w3.org/2000/svg";

function el(name, attrs) {
  const node = document.createElementNS(ns, name);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, String(v));
  return node;
}

function heatColour(value, peak) {
  if (!value) return "var(--heat-0)";
  /* Square root, not linear. Pick counts are heavily skewed, and a linear ramp
     puts one fast mover at the top and renders the whole middle of the
     distribution as one flat colour: exactly the part slotting moves. */
  const f = Math.sqrt(value / peak);
  const i = Math.min(4, 1 + Math.floor(f * 3));
  return `var(--heat-${i})`;
}

function drawFloor(svg, grid, peak, { flat = false } = {}) {
  svg.setAttribute("viewBox", `0 0 ${W} ${H}`);
  while (svg.lastChild && svg.lastChild.nodeName !== "title") svg.removeChild(svg.lastChild);

  for (let bay = 0; bay < DATA.bays; bay++) {
    for (let a = 0; a < DATA.aisles; a++) {
      for (const [i, side] of ["L", "R"].entries()) {
        const value = grid ? grid[bay][a * 2 + i] : 0;
        svg.appendChild(el("rect", {
          x: xOf(a, side), y: yOf(bay), width: CELL - 1, height: CELL - 1,
          fill: flat ? "var(--surface-2)" : heatColour(value, peak),
          stroke: "var(--line)", "stroke-width": 0.5, rx: 1,
        }));
      }
    }
  }
  /* The dock, where it actually is. "Near the dock" is the whole claim, and a
     plan without it cannot be checked by the reader. */
  svg.appendChild(el("rect", {
    x: PAD, y: PAD + DATA.bays * CELL + 4, width: CELL * 2 - 1, height: 6,
    fill: "var(--text)", rx: 1,
  }));
}

/* The S-shape route, in metres, matching `routing.s_shape`. Returns the path
   in SVG units and the distance in metres, so the readout and the drawing can
   never drift apart. */
function sShapeRoute(locs) {
  const deepest = new Map();
  for (const l of locs) {
    const y = (l.bay + 0.5) * BAY;
    if (y > (deepest.get(l.aisle) ?? -1)) deepest.set(l.aisle, y);
  }
  const aisles = [...deepest.keys()].sort((a, b) => a - b);

  const px = (metresX) => PAD + (metresX / PITCH) * (CELL * 2 + GAP) + CELL;
  const py = (metresY) => PAD + (metresY / BAY) * CELL;

  const pts = [[px(0), py(0)]];
  let metres = 0, x = 0, atBack = false;

  for (const [i, aisle] of aisles.entries()) {
    const ax = aisle * PITCH;
    metres += Math.abs(ax - x);
    x = ax;
    pts.push([px(x), py(atBack ? DEPTH : 0)]);

    const last = i === aisles.length - 1;
    if (last && !atBack) {
      const sweep = DEPTH + Math.abs(0 - ax);
      const turn = 2 * deepest.get(aisle) + Math.abs(0 - ax);
      if (turn <= sweep) {
        metres += turn;
        pts.push([px(x), py(deepest.get(aisle))], [px(x), py(0)], [px(0), py(0)]);
      } else {
        metres += sweep;
        pts.push([px(x), py(DEPTH)], [px(0), py(DEPTH)], [px(0), py(0)]);
      }
      return { pts, metres };
    }
    metres += DEPTH;
    atBack = !atBack;
    pts.push([px(x), py(atBack ? DEPTH : 0)]);
  }
  metres += Math.abs(0 - x);
  pts.push([px(0), py(atBack ? DEPTH : 0)]);
  if (atBack) { metres += DEPTH; pts.push([px(0), py(0)]); }
  return { pts, metres };
}

function drawRoute(svg, locs) {
  const { pts, metres } = sShapeRoute(locs);
  const d = pts.map((p, i) => `${i ? "L" : "M"}${p[0].toFixed(1)} ${p[1].toFixed(1)}`).join(" ");

  const path = el("path", {
    d, fill: "none", stroke: "var(--amber)", "stroke-width": 2,
    "stroke-linejoin": "round", "stroke-linecap": "round",
  });
  svg.appendChild(path);

  for (const l of locs) {
    svg.appendChild(el("rect", {
      x: xOf(l.aisle, l.side), y: yOf(l.bay), width: CELL - 1, height: CELL - 1,
      fill: "var(--amber)", rx: 1,
    }));
  }

  if (!prefersReduced) {
    const len = path.getTotalLength();
    path.style.strokeDasharray = String(len);
    path.style.strokeDashoffset = String(len);
    path.animate(
      [{ strokeDashoffset: len }, { strokeDashoffset: 0 }],
      { duration: 1500, easing: "ease-in-out", fill: "forwards" },
    );
  }
  return metres;
}

/* ------------------------------------------------------------------ scenes */

const peak = Math.max(
  ...DATA.before.flat(), ...DATA.after.flat(),
);

const floorBefore = document.getElementById("floor-before");
const floorAfter = document.getElementById("floor-after");
const routeTally = document.getElementById("route-tally");

function runRoute() {
  drawFloor(floorBefore, null, peak, { flat: true });
  drawFloor(floorAfter, null, peak, { flat: true });
  const b = drawRoute(floorBefore, DATA.sample.beforeLocs);
  const a = drawRoute(floorAfter, DATA.sample.afterLocs);
  const d = dict();
  routeTally.innerHTML =
    `<b>${b.toFixed(1)} m</b> &nbsp;&rarr;&nbsp; <b class="good">${a.toFixed(1)} m</b>`;
  return { b, a, d };
}

document.getElementById("route-play")?.addEventListener("click", runRoute);

const heat = document.getElementById("heat");
const heatToggle = document.getElementById("heat-toggle");
const heatTally = document.getElementById("heat-tally");

function paintHeat(optimised) {
  drawFloor(heat, optimised ? DATA.after : DATA.before, peak);
  /* Grouped by the page's language, not the browser's. `toLocaleString()` with
     no argument follows whatever the visitor's machine is set to, so an
     English page on a German laptop prints 6.623 and a German page on an
     English one prints 6,623. Both are wrong for the page they are on, and it
     is the kind of half-translated detail that undoes the rest of the work. */
  const n = (v) => v.toLocaleString(root.lang === "de" ? "de-DE" : "en-GB");
  heatTally.innerHTML = optimised
    ? `<b class="good">${n(DATA.optMetres)} m</b>`
    : `<b>${n(DATA.baseMetres)} m</b>`;
}

heatToggle?.addEventListener("click", () => {
  const next = heatToggle.getAttribute("aria-pressed") !== "true";
  heatToggle.setAttribute("aria-pressed", String(next));
  paintHeat(next);
});

/* ------------------------------------------------------------- translation */

const dict = () => STRINGS[root.lang] ?? STRINGS.en;

function applyLang(lang) {
  root.lang = lang;
  const d = dict();
  for (const node of document.querySelectorAll("[data-i18n]")) {
    const v = d[node.dataset.i18n];
    if (v !== undefined) node.textContent = v;
  }
  for (const node of document.querySelectorAll("[data-i18n-html]")) {
    const v = d[node.dataset.i18nHtml];
    if (v !== undefined) node.innerHTML = v;
  }
  const btn = document.getElementById("lang-btn");
  if (btn) btn.textContent = d["nav.lang"];
  if (d["meta.title"]) document.title = d["meta.title"];
  try { localStorage.setItem("slotting-lang", lang); } catch { /* private mode */ }

  /* The readouts carry numbers, and numbers are grouped differently in the two
     languages, so they have to be repainted rather than left as they were. */
  if (heatToggle) paintHeat(heatToggle.getAttribute("aria-pressed") === "true");
}

document.getElementById("lang-btn")?.addEventListener("click", () => {
  applyLang(root.lang === "de" ? "en" : "de");
});

document.getElementById("theme-btn")?.addEventListener("click", () => {
  const next = root.dataset.theme === "dark" ? "light" : "dark";
  root.dataset.theme = next;
  try { localStorage.setItem("slotting-theme", next); } catch { /* private mode */ }
});

/* --------------------------------------------------------------- first run */

applyLang(root.lang === "de" ? "de" : "en");
paintHeat(false);
runRoute();
